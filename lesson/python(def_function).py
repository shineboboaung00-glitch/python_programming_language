# ဥပမာ (၁) - အချက်အလက် (Parameter) မပါသော ရိုးရှင်းသည့် Function

# Function ကြေညာခြင်း
def greet():
    print("မင်္ဂလာပါ! Python မှ ကြိုဆိုပါတယ်။")

# Function ကို ခေါ်သုံးခြင်း (Call)
greet()

# ဥပမာ (၂) - အချက်အလက် (Parameter) ထည့်ပေးရသော Function

def greet_user(name):
    print("မင်္ဂလာပါ " + name + "၊ နေကောင်းရဲ့လား?")

# ခေါ်သုံးသည့်အခါ နာမည်ထည့်ပေးရန်
greet_user("Aung Aung")
greet_user("Su Su")

# ဥပမာ (၃) - ရလဒ်ကို ပြန်ထုတ်ပေးသည့် (return) Function

def add_numbers(a, b):
    result = a + b
    return result

# ရလဒ်ကို Variable ထဲသိမ်းပြီး ထုတ်ပြခြင်း
total = add_numbers(10, 20)
print("ပေါင်းလဒ်မှာ:", total)

# ၃။ def Function ကို ဘာကြောင့် သုံးသင့်တာလဲ?

# Code များ ထပ်ရေးစရာ မလိုခြင်း (Reusability): တစ်ခါရေးထားပြီးရင် လိုအပ်တဲ့နေရာတိုင်းမှာ Function နာမည်လေး ခေါ်လိုက်ရုံနဲ့ ပြန်သုံးလို့ရပါတယ်။

# Code ကို ဖတ်ရလွယ်ကူစေခြင်း (Readability): ရှည်လျားတဲ့ Code တွေကို အပိုင်းလိုက် ခွဲခြားထားနိုင်လို့ ဖတ်ရ၊ နားလည်ရ လွယ်ကူသွားပါတယ်။

# ပြင်ဆင်ရ လွယ်ကူခြင်း (Maintainability): Code မှာ အမှားပါရင် သို့မဟုတ် ပြင်ချင်ရင် အဲဒီ Function ထဲမှာပဲ ပြင်လိုက်ရုံနဲ့ အကုန် အလုပ်လုပ်သွားပါတယ်။