# Python မှာ file handling (ဖိုင်များကို ကိုင်တွယ်အသုံးပြုခြင်း) ဆိုတာ ဖိုင်တစ်ခုကို 
# ဖွင့်တာ (Open)၊ ဖတ်တာ (Read)၊ ရေးတာ/ပြင်တာ (Write/Append) နဲ့ 
# ပြန်ပိတ်တာ (Close) စတဲ့ အဆင့်တွေကို လုပ်ဆောင်ပေးတာဖြစ်ပါတယ်။

# ၁။ File Handling ရဲ့ အဓိက Mod (မုဒ်) များ
# ဖိုင်တစ်ခုကို ဖွင့်တဲ့အခါ ဘာလုပ်ချင်တာလဲဆိုတာကို Python ကို ပြောပြဖို့ mode ကို အသုံးပြုရပါတယ်။

# Mode	အမျိုးအစား	          အဓိပ္ပာယ်
# 'r'	    Read	        ဖိုင်ထဲက အချက်အလက်တွေကို ဖတ်ချင်ရုံပဲ (ဖိုင်မရှိရင် Error တက်မည်)

# 'w'	    Write	        ဖိုင်အသစ်ရေးမည်/ရှိပြီးသားဖိုင်ဆိုရင် အဟောင်းကို ဖျက်ပြီး အသစ်ပြန်ရေးမည်

# 'a'	    Append	        ရှိပြီးသားဖိုင်ရဲ့ အောက်မှာ စာအသစ်ဆက်ရေးမည် (အဟောင်းမပျက်ပါ)

# 'r+'	Read + Write	    ဖတ်ရော ရေးပါ နှစ်ခုလုံးလုပ်မည်

# ၂။ Open နဲ့ Close ပြုလုပ်နည်း (အခြေခံ)

# open() function ကိုသုံးပြီး ဖိုင်ကိုဖွင့်ကာ၊ လုပ်ဆောင်ပြီးပါက close() နဲ့ ပြန်ပိတ်ရပါတယ်။

# ဖိုင်အသစ်တစ်ခုဖန်တီးပြီး စာရေးခြင်း

file = open("sample.txt", "w")
file.write("Hello, World!\nWelcome to Python File Handling.")
file.close()  # ဖိုင်ကို ပြန်ပိတ်ရန် မမေ့ပါနဲ့

# ၃။ with statement ကို အသုံးပြုခြင်း (အကောင်းဆုံးနည်းလမ်း)
# ဖိုင်တွေကို ကိုင်တွယ်တဲ့အခါ close() လုပ်ဖို့ မေ့သွားတတ်တာကြောင့် 
# Python မှာ with ကို သုံးတာ အန္တရာယ်ကင်းပြီး အသုံးအများဆုံး နည်းလမ်းဖြစ်ပါတယ်။ 
# with block ပြီးတာနဲ့ ဖိုင်ကို အလိုအလျောက် ပြန်ပိတ်ပေးပါတယ်။

# စာဖတ်ခြင်း (Reading)

# ဖိုင်ထဲမှ စာများကို ဖတ်ချင်ပါက:
with open("sample.txt", "r") as file:
    content = file.read()
    print(content)

# စာကြောင်းတစ်ကြောင်းချင်းစီ ဖတ်ချင်ပါက:

with open("sample.txt", "r") as file:
    for line in file:
        print(line.strip())  # strip() က အပို space/newline များကို ဖယ်ပေးသည်

# စာဆက်ရေးခြင်း (Appending)
# ရှိပြီးသားဖိုင်ထဲက စာတွေကို မပျက်စေဘဲ နောက်ထပ် စာကြောင်းအသစ် ထပ်ပေါင်းချင်ရင် 'a' mode ကို သုံးရပါတယ်။

with open("sample.txt", "a") as file:
    file.write("\nThis line is appended.")

# ၄။ ဖိုင်ရှိမရှိ စစ်ဆေးခြင်းနှင့် ဖျက်ခြင်း (File Deletion)
# ဖိုင်တစ်ခုကို ဖျက်ချင်ရင် သို့မဟုတ် ဖိုင်ရှိမရှိ စစ်ချင်ရင် Python ရဲ့ os module ကို သုံးနိုင်ပါတယ်။

import os

# ဖိုင် ရှိ/မရှိ စစ်ဆေးပြီးမှ ဖျက်ခြင်း
if os.path.exists("sample.txt"):
    os.remove("sample.txt")
    print("ဖိုင်ကို ဖျက်ပြီးပါပြီ။")
else:
    print("ဖိုင် ရှာမတွေ့ပါ။")

# Pro Tip: ဖိုင်တွေကို ကိုင်တွယ်တဲ့အခါ အမြဲတမ်း with open(...) ကို 
# သုံးစွဲတာက memory leak မဖြစ်အောင်နဲ့ file lock ကျမကျန်ခဲ့အောင် 
# ကာကွယ်ပေးတဲ့ အကောင်းဆုံးအလေ့အကျင့်ဖြစ်ပါတယ်။