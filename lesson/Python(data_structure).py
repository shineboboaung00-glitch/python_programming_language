# Python မှာ Data Structure (ဒေတာ သိမ်းဆည်းသည့် တည်ဆောက်ပုံများ) 
# ဆိုတာ အချက်အလက်တွေကို စနစ်တကျ စုစည်းပြီး သိမ်းဆည်း၊ စီမံခန့်ခွဲနိုင်အောင် ပြုလုပ်ထားတဲ့ နည်းလမ်းတွေဖြစ်ပါတယ်။

# Python ရဲ့ အခြေခံအကျဆုံးနဲ့ အသုံးအများဆုံး Built-in Data Structures ၄ ခု

# ၁. List
# Data တန်ဖိုးတွေကို အစဉ်လိုက် (Ordered) သိမ်းဆည်းပေးပြီး တန်ဖိုးတွေကို ပြန်လည် ပြင်ဆင်ပြောင်းလဲလို့ရပါတယ် (Mutable)
# အချက်အလက် အမျိုးအစား မတူတာတွေကိုလည်း ရောသိမ်းလို့ရပါတယ်။

# သင်္ကေတ: [ ] (Square brackets)

# ထူးခြားချက်: တန်ဖိုးတူ တထပ်တည်း (Duplicates) သိမ်းဆည်းခွင့်ပြုသည်။

# နမူနာ:

fruits = ["apple", "banana", "cherry"]
fruits.append("orange")  # အသစ်ထည့်ခြင်း
fruits[0] = "mango"      # ပထမတန်ဖိုးကို ပြောင်းလဲခြင်း

# ၂. Tuple
# List နဲ့ ဆင်တူသော်လည်း တန်ဖိုးတွေကို တစ်ခါသတ်မှတ်ပြီးရင် ပြန်လည်ပြင်ဆင်ခွင့်မရှိပါ (Immutable)
# ပြောင်းလဲစရာမလိုတဲ့ ငြိမ်နေတဲ့ Data တွေကို သိမ်းဆည်းဖို့ အသုံးပြုပါတယ်။ 
# (List ထက် ပိုမိုမြန်ဆန်ပြီး Memory စား သက်သာပါတယ်)။

# သင်္ကေတ: ( ) (Parentheses)

# ထူးခြားချက်: တန်ဖိုးများကို ပြင်ဆင်/ဖျက်ဆီး၍ မရပါ။

# နမူနာ:

coordinates = (10, 20)
# coordinates[0] = 15  <-- ပြင်ရင် Error တက်ပါလိမ့်မယ်

# ၃. Dictionary
# Data တွေကို Key-Value Pair (သောော့ နှင့် တန်ဖိုး) စနစ်နဲ့ သိမ်းဆည်းပါတယ်။ 
# Key တစ်ခုချင်းစီဟာ Unique (မတူညီဘဲ သီးသန့်) ဖြစ်ရပါမယ်။ 
# တန်ဖိုးတွေကို Key နာမည်နဲ့ တိုက်ရိုက် ခေါ်ယူရှာဖွေနိုင်လို့ အလွန်မြန်ဆန်ပါတယ်။

# သင်္ကေတ: { Key: Value } (Curly braces with colon)

# ထူးခြားချက်: Key များမှတစ်ဆင့် တန်ဖိုးများကို ပြင်ဆင်/ဖတ်ယူနိုင်သည်။

# နမူနာ:

student = {
    "name": "Aung Aung",
    "age": 20,
    "major": "Computer Science"
}
print(student["name"])  # Output: Aung Aung

# ၄. Set (ဆက်)
# တန်ဖိုးအစဉ်လိုက် သတ်မှတ်ချက်မရှိဘဲ (Unordered) ထပ်နေတဲ့ တန်ဖိုးများကို လက်မခံဘဲ ပယ်ထုတ်ပေးပါသည် (Unique Values Only)။ သင်္ချာနည်းကျ Set Operations များ (Union, Intersection) ပြုလုပ်ရန် ကောင်းမွန်သည်။

# သင်္ကေတ: { } (Curly braces)

# ထူးခြားချက်: Duplicate values များကို အလိုအလျောက် ဖယ်ရှားပေးသည်။ Index နံပါတ်ဖြင့် ခေါ်ယူ၍ မရပါ။

# နမူနာ:

numbers = {1, 2, 2, 3, 4}
print(numbers)  # Output: {1, 2, 3, 4} (ထပ်နေသော 2 ကို ဖယ်ပေးသွားမည်)

# အနှစ်ချုပ် နှိုင်းယှဉ်ချက်

# Data Structure,Ordered (အစဉ်လိုက်),Mutable (ပြင်လို့ရ),Duplicates Allow (ထပ်လို့ရ),Syntax
# List,           YES,                  YES,             YES,                   [ ]
# Tuple,          YES,                  NO,              YES,                   ( )
# Dictionary,     YES,                  YES,             Key မရ / Value ရ,     {k:v}
# Set,            NO,                   YES,             NO,                    { }

