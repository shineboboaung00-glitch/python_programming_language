# Python မှာ try...except ဆိုတာက ကုဒ်ရေးတဲ့အခါ ဖြစ်လာနိုင်တဲ့ အမှားတွေကို ကြိုတင်ထိန်းချုပ်ပြီး 
# ပရိုဂရမ်တစ်ခုလုံး ရပ်သွား (crash) တာမျိုး မဖြစ်အောင် ကာကွယ်ပေးတဲ့ နည်းလမ်းတစ်ခုပါ။

# လွယ်လွယ်ပြောရရင် "အမှားဖြစ်နိုင်တဲ့ အလုပ်ကို try ထဲထည့်မယ်၊ အမှားဖြစ်လာရင် ဘာလုပ်ရမလဲဆိုတာကို "
# "except ထဲမှာ ရေးမယ်" ဆိုတဲ့ သဘောပါ။

# ၁။ အခြေခံ ပုံစံ
# ဥပမာအားဖြင့် ဂဏန်းနှစ်ခုကို စားတဲ့အခါ 0 နဲ့ စားမိရင် Error တက်တတ်ပါတယ်။ 
# အဲဒီလိုအချိန်မှာ try...except ကိုသုံးပြီး လှပစွာ ထိန်းချုပ်နိုင်ပါတယ်။

try:
    number = int(input("ဂဏန်းတစ်ခု ရိုက်ထည့်ပါ: "))
    result = 10 / number
    print(f"ရလဒ်ကတော့: {result}")
except ZeroDivisionError:
    print("အမှား! 0 နဲ့ စားလို့မရပါဘူး။")
except ValueError:
    print("အမှား! ဂဏန်းပဲ ရိုက်ထည့်ပေးပါ။")

# ၂။ အရေးကြီးတဲ့ အစိတ်အပိုင်းများ
# try...except မှာ နောက်ထပ်သုံးလေ့ရှိတဲ့ အရေးကြီးတဲ့ block နှစ်ခုရှိပါသေးတယ်။

# else: အမှားမရှိဘဲ အလုပ်က အဆင်ပြေသွားမှ လုပ်ဆောင်ပေးတဲ့အပိုင်း။

# finally: အမှားရှိသည်ဖြစ်စေ၊ မရှိသည်ဖြစ်စေ မဖြစ်မနေ လုပ်ဆောင်ပေးရမယ့်အပိုင်း 
# (ဥပမာ- ဖိုင်ဖွင့်ထားရင် ပြန်ပိတ်ပေးတာမျိုး)။

try:
    file = open("data.txt", "r")
    content = file.read()
except FileNotFoundError:
    print("ဖိုင်ကို ရှာမတွေ့ပါ။")
else:
    print("ဖိုင်ကို အောင်မြင်စွာ ဖတ်နိုင်ခဲ့ပါတယ်။")
finally:
    print("အစီအစဉ် ပြီးဆုံးပါပြီ။ (ဖိုင်ပိတ်ခြင်း စသည်တို့အတွက် အသုံးဝင်သည်)")

# ၃။ ဘယ်အချိန်မှာ သုံးသင့်လဲ?
# User input များ: User က စာသားနေရာမှာ ဂဏန်းရိုက်ထည့်တာ၊ ဂဏန်းနေရာမှာ စာရိုက်ထည့်တာမျိုးတွေကို စစ်ဆေးဖို့။

# File handling: ဖိုင်မရှိတာ၊ ဖတ်လို့မရတာမျိုးတွေကို ကိုင်တွယ်ဖို့။

# Network requests: အင်တာနက် လိုင်းကျနေတာ သို့မဟုတ် Server connection ပြတ်တောက်တာမျိုးတွေကို ဖမ်းဖို့။

# Note: Error တိုင်းကို except: လို့ပဲ ရေးတာထက် အထက်ပါပုံစံအတိုင်း 
# except ZeroDivisionError: ဆိုပြီး ဘာ Error လဲဆိုတာ သီးသန့်ဖမ်းပေးတာက 
# ကုဒ်ကို ပိုပြီး ကျွမ်းကျင်သပ်ရပ်စေပါတယ်။